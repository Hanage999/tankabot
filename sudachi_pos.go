func validateSudachiPartOfSpeech(pos []string) error {
	if len(pos) != 6 {
		return fmt.Errorf("品詞情報が6項目ではありません")
	}
	hierarchy := sudachiPOSHierarchy{pos[0], pos[1], pos[2], pos[3]}
	if _, ok := supportedSudachiPOSHierarchies[hierarchy]; !ok {
		return fmt.Errorf("未対応の品詞階層です: %s,%s,%s,%s", pos[0], pos[1], pos[2], pos[3])
	}
	return nil
}
